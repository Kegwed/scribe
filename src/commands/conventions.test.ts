import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { createFixtureRepo, type Files } from "../test/fixture-repo.ts";
import { MODELS } from "../llm.ts";
import { isSectionWrite, recordedLlm, scriptedLlm } from "../test/recorded-llm.ts";
import { generate } from "./generate.ts";
import { status } from "./status.ts";
import { update } from "./update.ts";

const ESLINT = [
  "export default [",
  "  {",
  "    rules: {",
  '      "prefer-const": "error",',
  '      "no-var": "error",',
  "    },",
  "  },",
  "];",
  "",
].join("\n");

const TARGET: Files = {
  "scribe.config.json": JSON.stringify({ modules: [{ name: "App", path: "src" }] }),
  "eslint.config.js": ESLINT,
  ".prettierrc": '{ "singleQuote": true }\n',
  "CONTRIBUTING.md": "# Contributing\n\n## Style\n\nName files in kebab-case.\n",
  "src/parse-input.ts": "export function parseInput(text: string): string[] {\n  return text.split(\",\");\n}\n",
};

const SECTION = "docs/guide/conventions.md";

function read(dir: string, path: string): string {
  return readFileSync(join(dir, path), "utf8");
}

const section = (...claims: [string, string[]][]) => ({
  paragraphs: [{ claims: claims.map(([text, evidence]) => ({ text, evidence })) }],
});

/**
 * The Module's Section is written first, with no Claims; Getting started has no
 * Evidence in these fixtures, so it asks nothing; Conventions gets `claims`.
 */
function conventionsLlm(...claims: [string, string[]][]) {
  return scriptedLlm([{ paragraphs: [] }, section(...claims)]);
}

describe("generate: Conventions", () => {
  it("writes Conventions with Claude, each Claim citing lint config, code or CONTRIBUTING, verified", async () => {
    const repo = createFixtureRepo(TARGET);
    const llm = recordedLlm("conventions");

    await generate(repo.dir, {}, { llm });

    const content = read(repo.dir, SECTION);
    expect(content).toMatch(/^# Conventions\n/);
    const [, ...prose] = content.split("\n\n").filter((block) => !block.startsWith("[^"));
    expect(prose.length).toBeGreaterThan(0);
    for (const paragraph of prose) expect(paragraph).toMatch(/\[\^\d+\]$/);
    expect(content).toMatch(/^\[\^\d+\]: (eslint\.config\.js|\.prettierrc|CONTRIBUTING\.md|src\/parse-input\.ts) \(.+\)$/m);
    expect(llm.calls.some((call) => call.model === MODELS.verify && call.prompt.includes("<claim>"))).toBe(true);
    const { sections } = JSON.parse(read(repo.dir, ".scribe/manifest.json"));
    expect(sections.conventions).toMatchObject({ file: SECTION, evidence: expect.arrayContaining([expect.anything()]) });
  });

  it("writes a Conventions Section citing lint and format config, code and CONTRIBUTING", async () => {
    const repo = createFixtureRepo(TARGET);
    const llm = conventionsLlm(
      ["Lint rules require `const` where a binding is never reassigned.", ["eslint.config.js"]],
      ["Strings use single quotes.", [".prettierrc"]],
      ["Files are named in kebab-case.", ["CONTRIBUTING.md#style", "src/parse-input.ts#parseInput"]],
    );

    const result = await generate(repo.dir, {}, { llm });

    expect(read(repo.dir, SECTION)).toBe([
      "# Conventions",
      "",
      "Lint rules require `const` where a binding is never reassigned.[^1] Strings use single quotes.[^2] Files are named in kebab-case.[^3][^4]",
      "",
      "[^1]: eslint.config.js (ESLint config)",
      "[^2]: .prettierrc (Prettier config)",
      "[^3]: CONTRIBUTING.md (Style)",
      "[^4]: src/parse-input.ts (parseInput)",
      "",
    ].join("\n"));
    expect(result.droppedClaims).toEqual([]);
    const { sections } = JSON.parse(read(repo.dir, ".scribe/manifest.json"));
    expect(sections.conventions).toMatchObject({
      file: SECTION,
      evidence: ["eslint.config.js", ".prettierrc", "CONTRIBUTING.md#style", "src/parse-input.ts#parseInput"].map((id) => ({ id, hash: expect.any(String) })),
    });
  });

  it("is current in status after generate, and Stale once the lint config it cites changes", async () => {
    const repo = createFixtureRepo(TARGET);
    await generate(repo.dir, {}, { llm: conventionsLlm(["Lint rules require `const`.", ["eslint.config.js"]]) });

    const before = (await status(repo.dir)).sections.find((s) => s.section === "conventions");
    repo.commit({ "eslint.config.js": ESLINT.replace('"no-var": "error"', '"no-var": "off"') });
    const after = (await status(repo.dir)).sections.find((s) => s.section === "conventions");

    expect(before).toMatchObject({ file: SECTION, stale: false, frozen: false, added: false });
    expect(after).toMatchObject({ stale: true, changedEvidence: ["eslint.config.js"] });
  });

  it("is regenerated by update when the lint config it cites changes, keeping what the change doesn't affect", async () => {
    const repo = createFixtureRepo(TARGET);
    await generate(repo.dir, {}, { llm: conventionsLlm(["Lint rules require `const`.", ["eslint.config.js"]]) });
    repo.commit({ "eslint.config.js": ESLINT.replace('"no-var": "error"', '"no-var": "off"') });

    const llm = scriptedLlm(section(["Lint rules require `const` and allow `var`.", ["eslint.config.js"]]));
    await update(repo.dir, {}, { llm });

    expect(read(repo.dir, SECTION)).toBe("# Conventions\n\nLint rules require `const` and allow `var`.[^1]\n\n[^1]: eslint.config.js (ESLint config)\n");
    const writes = llm.calls.filter(isSectionWrite);
    expect(writes).toHaveLength(1);
    expect(writes[0]!.prompt).toContain('<changed id="eslint.config.js" status="changed"/>');
    expect(writes[0]!.prompt).toContain("Lint rules require `const`.[^1]");
  });

  it("writes a bare Conventions, without asking the LLM, when the repo has code but no lint config or CONTRIBUTING", async () => {
    const repo = createFixtureRepo({ "scribe.config.json": TARGET["scribe.config.json"]!, "src/parse-input.ts": TARGET["src/parse-input.ts"]! });
    const llm = scriptedLlm({ paragraphs: [] });

    await generate(repo.dir, {}, { llm });

    expect(read(repo.dir, SECTION)).toBe("# Conventions\n");
    expect(llm.calls.filter(isSectionWrite).some((call) => call.prompt.includes("parseInput") && !call.prompt.startsWith("Module:"))).toBe(false);
  });

  it("is written from CONTRIBUTING alone", async () => {
    const { "eslint.config.js": _, ".prettierrc": __, "src/parse-input.ts": ___, ...rest } = TARGET;
    const repo = createFixtureRepo(rest);
    const llm = scriptedLlm(section(["Files are named in kebab-case.", ["CONTRIBUTING.md#style"]]));

    await generate(repo.dir, {}, { llm });

    expect(read(repo.dir, SECTION)).toBe("# Conventions\n\nFiles are named in kebab-case.[^1]\n\n[^1]: CONTRIBUTING.md (Style)\n");
  });

  it("reads lint config in workspace packages, but never in the Guide, hidden directories or node_modules", async () => {
    const repo = createFixtureRepo({
      ...TARGET,
      "packages/web/.eslintrc.json": '{ "rules": { "eqeqeq": "error" } }\n',
      "docs/guide/.eslintrc.json": "{}\n",
      ".github/linters/.eslintrc.json": "{}\n",
      "node_modules/x/.prettierrc": "{}\n",
    });
    const llm = conventionsLlm(["The web package requires `===`.", ["packages/web/.eslintrc.json"]]);

    await generate(repo.dir, {}, { llm });

    expect(read(repo.dir, SECTION)).toContain("[^1]: packages/web/.eslintrc.json (ESLint config)");
    const prompt = llm.calls.filter(isSectionWrite).at(-1)!.prompt;
    expect(prompt).not.toContain("docs/guide/.eslintrc.json");
    expect(prompt).not.toContain(".github/linters");
    expect(prompt).not.toContain("node_modules");
  });

  it("removes a Claim that cites no Conventions Evidence, or that the verifier rejects, and reports it", async () => {
    const repo = createFixtureRepo(TARGET);
    const llm = scriptedLlm(
      [{ paragraphs: [] }, section(
        ["Strings use single quotes.", [".prettierrc"]],
        ["Tests sit beside their code.", ["README.md"]],
        ["Every function is async.", ["src/parse-input.ts#parseInput"]],
      )],
      { "Every function is async.": { confirmed: false, reason: "parseInput is synchronous" } },
    );

    const result = await generate(repo.dir, {}, { llm });

    expect(read(repo.dir, SECTION)).toBe("# Conventions\n\nStrings use single quotes.[^1]\n\n[^1]: .prettierrc (Prettier config)\n");
    expect(result.droppedClaims).toEqual([
      { section: "conventions", text: "Tests sit beside their code.", reason: "cites no lint or format config, code or CONTRIBUTING passage" },
      { section: "conventions", text: "Every function is async.", reason: "parseInput is synchronous" },
    ]);
  });

  it("never overwrites a Conventions a human edited, and reports it Frozen", async () => {
    const repo = createFixtureRepo({ ...TARGET, [SECTION]: "# House style\n" });

    const result = await generate(repo.dir, {}, { llm: conventionsLlm(["Strings use single quotes.", [".prettierrc"]]) });

    expect(read(repo.dir, SECTION)).toBe("# House style\n");
    expect(result.frozen).toContain("conventions");
  });

  it("counts Conventions in the cost estimate", async () => {
    const repo = createFixtureRepo(TARGET);
    const llm = scriptedLlm("unused");
    let sections: { section: string; tokens: number }[] = [];

    await generate(repo.dir, { confirm: async (estimate) => ((sections = estimate.sections), false) }, { llm });

    expect(sections.find((s) => s.section === "conventions")?.tokens).toBeGreaterThan(0);
    expect(llm.calls).toEqual([]);
  });

  it("writes a Proposal beside a Conventions a human edited once the lint config it cites changes", async () => {
    const repo = createFixtureRepo(TARGET);
    await generate(repo.dir, {}, { llm: conventionsLlm(["Lint rules require `const`.", ["eslint.config.js"]]) });
    repo.commit({ [SECTION]: "# House style\n", "eslint.config.js": ESLINT.replace('"no-var": "error"', '"no-var": "off"') });

    const result = await update(repo.dir, {}, { llm: scriptedLlm(section(["Lint rules allow `var`.", ["eslint.config.js"]])) });

    expect(read(repo.dir, SECTION)).toBe("# House style\n");
    expect(result.proposals).toEqual([{ section: "conventions", file: "docs/guide/conventions.proposal.md" }]);
    expect(read(repo.dir, "docs/guide/conventions.proposal.md")).toBe("# Conventions\n\nLint rules allow `var`.[^1]\n\n[^1]: eslint.config.js (ESLint config)\n");
  });

  it("is not Stale when a lint config it doesn't cite changes", async () => {
    const repo = createFixtureRepo(TARGET);
    await generate(repo.dir, {}, { llm: conventionsLlm(["Lint rules require `const`.", ["eslint.config.js"]]) });
    repo.commit({ ".prettierrc": '{ "singleQuote": false }\n' });

    const after = (await status(repo.dir)).sections.find((s) => s.section === "conventions");

    expect(after).toMatchObject({ stale: false });
  });
});
